import * as React from "react"
import { useParams, Navigate, useNavigate } from "react-router-dom"
import { ArrowLeft, ExternalLink } from "lucide-react"

import { MainLayout } from "@/components/layout/MainLayout"
import { Button } from "@/components/ui/button"

export default function ReportDetailPage() {
  const { orgSlug, id } = useParams<{ orgSlug: string; id: string }>()
  const navigate = useNavigate()

  if (!orgSlug) {
    return <Navigate to="/pending-access" replace />
  }

  if (!id) {
    return (
      <MainLayout header={{ breadcrumbs: [] }}>
        <div className="flex min-h-[50vh] items-center justify-center p-8 text-center text-red-500">
          Missing report ID.
        </div>
      </MainLayout>
    )
  }

  const tz = Intl.DateTimeFormat().resolvedOptions().timeZone
  const pdfUrl = `${window.location.origin}/api/v1/orgs/${orgSlug}/compliance-reports/${id}/pdf?timezone=${encodeURIComponent(tz)}`

  return (
    <MainLayout
      header={{
        breadcrumbs: [
          { label: "Reports", to: `/orgs/${encodeURIComponent(orgSlug)}/reports` },
          { label: "Report View" },
        ],
      }}
    >
      <div className="flex h-[calc(100vh-100px)] w-full flex-col gap-4">
        {/* Header Actions */}
        <div className="flex items-center justify-between">
          <div className="flex items-center gap-4">
            <Button
              variant="ghost"
              size="icon"
              className="h-8 w-8 rounded-full"
              onClick={() => navigate(-1)}
            >
              <ArrowLeft className="h-4 w-4" />
            </Button>
            <div>
              <h1 className="text-xl font-bold text-foreground">Compliance Report View</h1>
              <p className="text-xs text-muted-foreground">
                Displaying the official PDF generated by the compliance engine.
              </p>
            </div>
          </div>
          <div className="flex items-center gap-3">
            <Button
              variant="outline"
              className="gap-2 font-semibold"
              onClick={() => window.open(pdfUrl, "_blank")}
            >
              <ExternalLink className="h-4 w-4" />
              Open in New Tab
            </Button>
            <Button
              className="gap-2 bg-[#128BDA] font-semibold text-white hover:bg-[#128BDA]/90"
              onClick={() => {
                const a = document.createElement("a")
                a.href = pdfUrl
                a.download = `report_${id}.pdf`
                document.body.appendChild(a)
                a.click()
                document.body.removeChild(a)
              }}
            >
              Download PDF
            </Button>
          </div>
        </div>

        {/* Embedded PDF */}
        <div className="flex-1 overflow-hidden rounded-xl border border-border bg-card shadow-sm">
          <iframe
            src={`${pdfUrl}#view=FitH`}
            title="Compliance Report PDF"
            className="h-full w-full border-none bg-muted/20"
          />
        </div>
      </div>
    </MainLayout>
  )
}
